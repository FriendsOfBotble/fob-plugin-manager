<?php

namespace FriendsOfBotble\PluginManager\Services;

use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Validator;
use Illuminate\Support\Str;
use Illuminate\Validation\ValidationException;
use Throwable;
use ZipArchive;

/**
 * Stores, validates and safely extracts plugin ZIP archives.
 *
 * Every path that touches the filesystem is derived on the server: uploads are
 * stored under a random name in storage/app/tmp, archive entries are checked for
 * path traversal before anything is extracted, and the destination folder comes
 * from the archive's own plugin.json (restricted to [A-Za-z0-9_-]).
 */
class PluginZipHandler
{
    protected const TMP_DIRECTORY = 'app/tmp';

    /**
     * Everything this plugin writes to the shared tmp directory starts with this
     * prefix, so pruning never touches files that belong to other code.
     */
    protected const TMP_PREFIX = 'fob-plugin-manager-';

    protected const STORED_FILE_PATTERN = '/^fob-plugin-manager-upload-[A-Za-z0-9]{40}\.zip$/D';

    /** Unconfirmed uploads and staging folders older than this are removed. */
    protected const STALE_AFTER_SECONDS = 86400;

    /** Backups are kept longer: they are the only copy if PHP died mid-swap. */
    protected const STALE_BACKUP_AFTER_SECONDS = 604800;

    public function tmpPath(string $name = ''): string
    {
        return storage_path(self::TMP_DIRECTORY . ($name !== '' ? '/' . $name : ''));
    }

    /**
     * Move an uploaded archive into the tmp directory and return its stored basename.
     */
    public function store(UploadedFile $file): string
    {
        $this->pruneStale();

        $storedName = self::TMP_PREFIX . 'upload-' . Str::random(40) . '.zip';

        $file->move($this->tmpPath(), $storedName);

        return $storedName;
    }

    /**
     * Resolve a stored basename to an absolute path. Anything that is not a bare
     * name generated by store() is rejected, so no other file can be targeted.
     */
    public function resolveStoredFile(?string $storedName): ?string
    {
        if (! $storedName || ! preg_match(self::STORED_FILE_PATTERN, $storedName)) {
            return null;
        }

        $path = $this->tmpPath($storedName);

        return File::isFile($path) ? $path : null;
    }

    /**
     * Open an archive and reject it if any entry could escape the extraction directory.
     */
    public function open(string $path): ZipArchive
    {
        $zip = new ZipArchive();

        if ($zip->open($path) !== true) {
            throw $this->error(trans('plugins/fob-plugin-manager::plugin-manager.plugin_upload.validation.invalid_zip_file'));
        }

        for ($index = 0; $index < $zip->numFiles; $index++) {
            $entryName = $zip->getNameIndex($index);

            if ($entryName === false || ! $this->isSafeEntryName($entryName)) {
                $zip->close();

                throw $this->error(trans('plugins/fob-plugin-manager::plugin-manager.plugin_upload.validation.unsafe_zip_entry'));
            }
        }

        return $zip;
    }

    /**
     * An entry is safe when it is relative and has no "..", drive prefix or null byte.
     */
    public function isSafeEntryName(string $entryName): bool
    {
        if ($entryName === '' || str_contains($entryName, "\0")) {
            return false;
        }

        $normalized = str_replace('\\', '/', $entryName);

        if (str_starts_with($normalized, '/') || preg_match('/^[A-Za-z]:/', $normalized)) {
            return false;
        }

        return ! in_array('..', explode('/', $normalized), true);
    }

    /**
     * Find and validate plugin.json, either at the archive root or inside a single
     * top-level folder. Returns [entry prefix, plugin.json content, plugin folder name].
     */
    public function readPluginManifest(ZipArchive $zip): array
    {
        $prefix = $this->detectRootPrefix($zip);

        $content = $prefix === null ? false : $zip->getFromName($prefix . 'plugin.json');

        if (! $content) {
            throw $this->error(trans('plugins/fob-plugin-manager::plugin-manager.plugin_upload.validation.could_not_find_plugin_file'));
        }

        $manifest = json_decode($content, true);

        if (! is_array($manifest)) {
            throw $this->error(trans('plugins/fob-plugin-manager::plugin-manager.plugin_upload.validation.invalid_plugin_file'));
        }

        $validator = Validator::make($manifest, [
            'id' => ['required', 'string', 'regex:/^[A-Za-z0-9_-]+\/[A-Za-z0-9_-]+$/D'],
            'name' => ['required', 'string'],
            'namespace' => ['required', 'string'],
            'provider' => ['required', 'string'],
            'author' => ['required', 'string'],
            'url' => ['nullable', 'url'],
            'version' => ['required', 'string'],
            'description' => ['nullable', 'string'],
            'minimum_core_version' => ['nullable', 'string', 'regex:/^[0-9]+\.[0-9]+\.[0-9]+$/D'],
        ]);

        if ($validator->fails()) {
            throw ValidationException::withMessages(['file' => $validator->errors()->all()]);
        }

        $pluginName = Str::afterLast($manifest['id'], '/');

        if (! preg_match('/^[A-Za-z0-9_-]+$/D', $pluginName)) {
            throw $this->error(trans('plugins/fob-plugin-manager::plugin-manager.plugin_upload.validation.invalid_plugin_file'));
        }

        return [$prefix, $manifest, $pluginName];
    }

    /**
     * Install a new plugin. The destination folder must not exist yet.
     */
    public function extractTo(ZipArchive $zip, string $prefix, string $destination): void
    {
        if (File::exists($destination)) {
            throw $this->error(trans('plugins/fob-plugin-manager::plugin-manager.plugin_upload.validation.plugin_directory_exists'));
        }

        $this->withStagedPlugin($zip, $prefix, fn (string $source) => $this->moveDirectory($source, $destination));
    }

    /**
     * Replace an installed plugin. The archive is fully extracted to staging first, so
     * the live folder is only swapped out for the duration of two renames, and the
     * previous copy is restored if the swap fails.
     */
    public function replace(ZipArchive $zip, string $prefix, string $destination): void
    {
        $this->withStagedPlugin($zip, $prefix, function (string $source) use ($destination): void {
            $backup = $this->tmpPath(self::TMP_PREFIX . 'backup-' . Str::random(16));

            $this->moveDirectory($destination, $backup);

            try {
                $this->moveDirectory($source, $destination);
            } catch (Throwable $exception) {
                // moveDirectory() never leaves a partial copy behind, so the destination is
                // either empty or was created by someone else; restore only into a free slot.
                try {
                    $this->moveDirectory($backup, $destination);
                } catch (Throwable) {
                    // The backup stays in tmp (kept for STALE_BACKUP_AFTER_SECONDS) for manual recovery.
                }

                throw $exception;
            }

            File::deleteDirectory($backup);
        });
    }

    /**
     * Extract the archive into a private staging folder and hand the plugin root to
     * $callback. Anything beside the root (e.g. __MACOSX/) is discarded with staging.
     */
    protected function withStagedPlugin(ZipArchive $zip, string $prefix, callable $callback): void
    {
        $staging = $this->tmpPath(self::TMP_PREFIX . 'stage-' . Str::random(16));

        try {
            if (! $zip->extractTo($staging)) {
                throw $this->error(trans('plugins/fob-plugin-manager::plugin-manager.plugin_upload.validation.extract_failed'));
            }

            $source = $prefix === '' ? $staging : $staging . '/' . rtrim($prefix, '/');

            if (! File::isDirectory($source)) {
                throw $this->error(trans('plugins/fob-plugin-manager::plugin-manager.plugin_upload.validation.extract_failed'));
            }

            $callback($source);
        } finally {
            File::deleteDirectory($staging);
        }
    }

    /**
     * Return "" when plugin.json is at the root, "folder/" when it sits inside exactly
     * one top-level folder, or null when it cannot be located unambiguously.
     */
    protected function detectRootPrefix(ZipArchive $zip): ?string
    {
        if ($zip->locateName('plugin.json') !== false) {
            return '';
        }

        $folders = [];

        for ($index = 0; $index < $zip->numFiles; $index++) {
            if (preg_match('#^([^/]+)/plugin\.json$#D', (string) $zip->getNameIndex($index), $matches)
                && $matches[1] !== '__MACOSX') {
                $folders[$matches[1]] = true;
            }
        }

        return count($folders) === 1 ? array_key_first($folders) . '/' : null;
    }

    /**
     * rename() is atomic on the same filesystem; fall back to copy + delete across devices.
     */
    protected function moveDirectory(string $from, string $to): void
    {
        // Never merge into an existing folder (e.g. a concurrent install of the same plugin).
        if (File::exists($to)) {
            throw $this->error(trans('plugins/fob-plugin-manager::plugin-manager.plugin_upload.validation.plugin_directory_exists'));
        }

        if (@rename($from, $to)) {
            return;
        }

        if (! File::copyDirectory($from, $to)) {
            // $to did not exist before this call, so whatever is there is our partial copy.
            File::deleteDirectory($to);

            throw $this->error(trans('plugins/fob-plugin-manager::plugin-manager.plugin_upload.validation.extract_failed'));
        }

        File::deleteDirectory($from);
    }

    /**
     * Remove leftovers: uploads whose update was never confirmed, and staging or
     * backup folders left behind when PHP was killed mid-request.
     */
    public function pruneStale(): void
    {
        $now = time();

        foreach (File::glob($this->tmpPath(self::TMP_PREFIX . '*')) ?: [] as $path) {
            $maxAge = str_starts_with(basename($path), self::TMP_PREFIX . 'backup-')
                ? self::STALE_BACKUP_AFTER_SECONDS
                : self::STALE_AFTER_SECONDS;

            if ($now - (int) @filemtime($path) < $maxAge) {
                continue;
            }

            File::isDirectory($path) ? File::deleteDirectory($path) : File::delete($path);
        }
    }

    protected function error(string $message): ValidationException
    {
        return ValidationException::withMessages(['file' => $message]);
    }
}
